def timezone_to_country(tz_name: str):
    """Look up country name for a given IANA timezone name."""
    if not tz_name:
        return None
    tz_name = tz_name.strip()
    direct = _ZONE_TO_COUNTRY.get(tz_name)
    if direct:
        return direct
    parts = tz_name.split("/")
    if len(parts) >= 2:
        city = parts[1]
        for key, country in _ZONE_TO_COUNTRY.items():
            if key.endswith("/" + city):
                return country
    return None
